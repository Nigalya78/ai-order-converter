import React from 'react';
import { Sparkles, RefreshCw, ChevronRight, Menu, AlertCircle } from 'lucide-react';
import type { NavTab } from './Sidebar';

interface HeaderProps {
  currentTab: NavTab;
  onNavigateToOrders: () => void;
  onNewOrderClick: () => void;
  onToggleMobileMenu?: () => void;
  onRefresh?: () => void;
  isRefreshing?: boolean;
  selectedOrderId?: number | null;
  apiConnected?: boolean | null;
}

export const Header: React.FC<HeaderProps> = ({
  currentTab,
  onNavigateToOrders,
  onNewOrderClick,
  onToggleMobileMenu,
  onRefresh,
  isRefreshing = false,
  selectedOrderId,
  apiConnected,
}) => {
  const titles: Record<NavTab, { title: string; subtitle: string; shortTitle: string }> = {
    dashboard: {
      title: 'Operations Dashboard',
      shortTitle: 'Dashboard',
      subtitle: 'Real-time overview of customer orders, revenue, and conversion health',
    },
    chat: {
      title: 'Conversational AI Chat-to-Order',
      shortTitle: 'AI Chat',
      subtitle: 'Natural multi-turn conversation for snack exploration, draft cart management, and ordering',
    },
    orders: {
      title: selectedOrderId ? `Order Details #${selectedOrderId}` : 'Order Registry',
      shortTitle: selectedOrderId ? `Order #${selectedOrderId}` : 'Orders',
      subtitle: selectedOrderId
        ? 'Detailed item breakdown, customer message log, and lifecycle status'
        : 'Review, modify, and track customer snack orders generated by the AI',
    },
    'message-to-order': {
      title: 'AI Message-to-Order Converter',
      shortTitle: 'AI Converter',
      subtitle: 'Extract orders, enquiries, and line items directly from customer text messages',
    },
    catalog: {
      title: 'Product Catalogue & Pricing',
      shortTitle: 'Catalogue',
      subtitle: 'Configured South Indian snacks and weight variants recognized by the order engine',
    },
  };

  const { title, shortTitle, subtitle } = titles[currentTab];

  return (
    <header className="h-14 sm:h-16 px-3 sm:px-6 lg:px-8 border-b border-slate-200/90 bg-white/95 backdrop-blur-xs flex items-center justify-between sticky top-0 z-30 shadow-2xs no-print transition-all">
      {}
      <div className="flex items-center gap-2 sm:gap-3 min-w-0 flex-1">
        {onToggleMobileMenu && (
          <button
            type="button"
            onClick={onToggleMobileMenu}
            className="lg:hidden p-1.5 -ml-1 text-slate-600 hover:text-slate-900 hover:bg-slate-100 active:bg-slate-200 rounded-xl transition-colors shrink-0"
            aria-label="Open navigation menu"
          >
            <Menu size={20} />
          </button>
        )}

        <div className="min-w-0 flex-1">
          {}
          <div className="hidden sm:flex items-center gap-1 text-[11px] text-slate-500 mb-0.5 font-medium">
            {selectedOrderId && currentTab === 'orders' ? (
              <div className="flex items-center gap-1">
                <button
                  type="button"
                  onClick={onNavigateToOrders}
                  className="hover:text-indigo-600 transition-colors"
                >
                  Orders
                </button>
                <ChevronRight size={11} className="text-slate-400" />
                <span className="font-semibold text-slate-800">Order #{selectedOrderId}</span>
              </div>
            ) : (
              <span className="capitalize text-slate-400">
                Operations &gt; {currentTab.replace('-', ' ')}
              </span>
            )}
          </div>

          {}
          <div className="flex items-center gap-2 min-w-0">
            <h1
              className="text-sm sm:text-base lg:text-lg font-bold text-slate-900 tracking-tight truncate"
              title={title}
            >
              <span className="sm:hidden">{shortTitle}</span>
              <span className="hidden sm:inline">{title}</span>
            </h1>

            {}
            <div className="sm:hidden shrink-0 flex items-center" title={`API is ${apiConnected ? 'Online' : 'Offline'}`}>
              {apiConnected === true && (
                <span className="inline-block h-2 w-2 rounded-full bg-emerald-500 ring-2 ring-emerald-100 animate-pulse" />
              )}
              {apiConnected === false && (
                <span className="inline-block h-2 w-2 rounded-full bg-rose-500 ring-2 ring-rose-100" />
              )}
            </div>
          </div>

          <p className="text-xs text-slate-500 hidden lg:block leading-tight mt-0.5 truncate max-w-xl">
            {subtitle}
          </p>
        </div>
      </div>

      {}
      <div className="flex items-center gap-1.5 sm:gap-2.5 shrink-0 ml-2">
        {}
        <div className="hidden md:flex items-center mr-1">
          {apiConnected === true && (
            <span className="inline-flex items-center gap-1.5 text-[11px] font-semibold text-emerald-700 bg-emerald-50 border border-emerald-200/80 px-2.5 py-1 rounded-full">
              <span className="h-1.5 w-1.5 rounded-full bg-emerald-500 animate-pulse" />
              API Online
            </span>
          )}
          {apiConnected === false && (
            <span className="inline-flex items-center gap-1.5 text-[11px] font-semibold text-rose-700 bg-rose-50 border border-rose-200/80 px-2.5 py-1 rounded-full">
              <AlertCircle size={12} className="text-rose-500" />
              API Offline
            </span>
          )}
        </div>

        {}
        {onRefresh && (
          <button
            type="button"
            onClick={onRefresh}
            disabled={isRefreshing}
            className="inline-flex items-center justify-center gap-1.5 p-2 sm:px-3 sm:py-1.5 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 active:bg-slate-300 rounded-xl transition-all disabled:opacity-50 shadow-2xs"
            title="Refresh order data from API"
            aria-label="Refresh data"
          >
            <RefreshCw size={13} className={isRefreshing ? 'animate-spin text-indigo-600' : ''} />
            <span className="hidden sm:inline">Refresh</span>
          </button>
        )}

        {}
        {currentTab !== 'message-to-order' && (
          <button
            type="button"
            onClick={onNewOrderClick}
            className="inline-flex items-center justify-center gap-1 px-2.5 py-1.5 sm:px-3.5 sm:py-1.5 text-xs font-semibold text-white bg-indigo-600 hover:bg-indigo-700 active:bg-indigo-800 rounded-xl shadow-xs transition-all hover:scale-[1.01]"
            title="Convert customer message into order"
          >
            <Sparkles size={13} className="shrink-0" />
            <span className="sm:hidden text-[11px]">New</span>
            <span className="hidden sm:inline">Convert Message</span>
          </button>
        )}
      </div>
    </header>
  );
};
